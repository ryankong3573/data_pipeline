with DAILY_ETH_SUMMARY as (
    SELECT 
    DATE(INTERVAL_BEGIN) AS "DAY",
    MIN_BY("OPEN", INTERVAL_BEGIN) AS "OPEN",
    MAX_BY("CLOSE", INTERVAL_BEGIN) AS "CLOSE",
    MIN("LOW") AS "LOW",
    MAX("HIGH") AS "HIGH",
    SUM("TRADES") AS "DAILY_TRADES",
    SUM("VOLUME") AS "DAILY_VOLUME"
    FROM {{ref("stg_btc")}} GROUP BY DATE(INTERVAL_BEGIN)
) SELECT * FROM DAILY_ETH_SUMMARY